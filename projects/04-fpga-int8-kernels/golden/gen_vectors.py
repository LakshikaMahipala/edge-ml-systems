"""Generate random test vectors + expected outputs for the RTL testbenches.

Writes into vectors/ (one value per line, two's-complement hex, as read by
$readmemh) and vectors/config.svh with the matching sizes, so the RTL
parameters, the testbench and the golden model can never disagree.

    python golden/gen_vectors.py [--seed 0] [--tests 200]
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from int8_ref import dwconv1d_int8, fc_int8, fxp_add, fxp_mul

FC = dict(IN=16, OUT=8, SHIFT=8)
DW = dict(C=4, L=32, K=3, SHIFT=7)
FXP_FRAC = 7  # Q1.7


def write_hex(path: Path, values, bits: int) -> None:
    mask = (1 << bits) - 1
    digits = bits // 4
    with path.open("w") as f:
        for v in np.asarray(values).ravel():
            f.write(f"{int(v) & mask:0{digits}x}\n")


def random_int8(rng, shape):
    x = rng.integers(-128, 128, size=shape)
    # Make the first two test vectors extreme to exercise saturation paths.
    x.reshape(shape[0], -1)[0] = 127
    if shape[0] > 1:
        x.reshape(shape[0], -1)[1] = -128
    return x.astype(np.int8)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--tests", type=int, default=200)
    ap.add_argument("--out", default="vectors")
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    n = args.tests

    # Fully-connected layer
    w = rng.integers(-128, 128, size=(FC["OUT"], FC["IN"])).astype(np.int8)
    b = rng.integers(-(1 << 12), 1 << 12, size=FC["OUT"]).astype(np.int32)
    x = random_int8(rng, (n, FC["IN"]))
    y = fc_int8(x, w, b, FC["SHIFT"])
    write_hex(out / "fc_weights.hex", w, 8)
    write_hex(out / "fc_bias.hex", b, 32)
    write_hex(out / "fc_x.hex", x, 8)
    write_hex(out / "fc_y.hex", y, 8)

    # Depthwise conv
    w = rng.integers(-128, 128, size=(DW["C"], DW["K"])).astype(np.int8)
    b = rng.integers(-(1 << 10), 1 << 10, size=DW["C"]).astype(np.int32)
    x = random_int8(rng, (n, DW["C"], DW["L"]))
    y = dwconv1d_int8(x, w, b, DW["SHIFT"])
    write_hex(out / "dw_weights.hex", w, 8)
    write_hex(out / "dw_bias.hex", b, 32)
    write_hex(out / "dw_x.hex", x, 8)
    write_hex(out / "dw_y.hex", y, 8)

    # Fixed-point primitives: every (a, b) pair of int8 values, a-major order
    a, bb = np.meshgrid(np.arange(-128, 128), np.arange(-128, 128), indexing="ij")
    write_hex(out / "fxp_mul_y.hex", fxp_mul(a, bb, FXP_FRAC), 8)
    write_hex(out / "fxp_add_y.hex", fxp_add(a, bb), 8)

    sat = float(np.mean((y == 127) | (y == -128)))
    (out / "config.svh").write_text(
        "// Generated by golden/gen_vectors.py — do not edit.\n"
        f"`define N_TESTS {n}\n"
        + "".join(f"`define FC_{k} {v}\n" for k, v in FC.items())
        + "".join(f"`define DW_{k} {v}\n" for k, v in DW.items())
        + f"`define FXP_FRAC {FXP_FRAC}\n")
    print(f"wrote {n} FC and depthwise-conv test vectors to {out}/ "
          f"(depthwise outputs saturated: {100 * sat:.0f}%)")


if __name__ == "__main__":
    main()
